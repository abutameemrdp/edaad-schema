import { useState } from 'react';

interface ToolbarProps {
  schema: any[];
  onClear: () => void;
  onFitView: () => void;
}

function generateSQL(schema: any[]): string {
  if (!schema || schema.length === 0) return '-- No tables in schema';
  let sql = '-- Generated by Edaad AI Schema Architect\n-- ' + new Date().toISOString() + '\n\n';
  schema.forEach(t => {
    sql += `CREATE TABLE ${t.tableName} (\n`;
    const cols = (t.columns ?? []).map((c: any) => {
      let def = `  ${c.name} ${c.type.toUpperCase()}`;
      if (c.isPrimary) def += ' PRIMARY KEY';
      return def;
    });
    sql += cols.join(',\n');
    sql += `\n);\n\n`;
  });
  return sql;
}

export function Toolbar({ schema, onClear, onFitView }: ToolbarProps) {
  const [showSQL, setShowSQL] = useState(false);
  const [copied, setCopied] = useState(false);

  const totalColumns = schema.reduce((sum, t) => sum + (t.columns?.length ?? 0), 0);
  const totalRelations = schema.reduce((sum, t) => sum + (t.relations?.length ?? 0), 0);
  const sql = generateSQL(schema);

  const copySQL = async () => {
    await navigator.clipboard.writeText(sql);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <>
      <div className="toolbar glass-panel">
        <div className="toolbar-stats">
          <span className="stat-badge">
            <span className="stat-icon">📊</span>
            <span>{schema.length} جداول</span>
          </span>
          <span className="stat-badge">
            <span className="stat-icon">📋</span>
            <span>{totalColumns} أعمدة</span>
          </span>
          {totalRelations > 0 && (
            <span className="stat-badge">
              <span className="stat-icon">🔗</span>
              <span>{totalRelations} علاقات</span>
            </span>
          )}
        </div>

        <div className="toolbar-actions">
          <button className="tb-btn" onClick={onFitView} title="Fit View">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M15 3h6v6M9 21H3v-6M21 3l-7 7M3 21l7-7"/>
            </svg>
            <span>عرض كامل</span>
          </button>

          <button className="tb-btn tb-btn-blue" onClick={() => setShowSQL(true)} title="Export SQL">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/><polyline points="7 10 12 15 17 10"/><line x1="12" y1="15" x2="12" y2="3"/>
            </svg>
            <span>تصدير SQL</span>
          </button>

          {schema.length > 0 && (
            <button className="tb-btn tb-btn-danger" onClick={onClear} title="Clear">
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <polyline points="3 6 5 6 21 6"/><path d="M19 6l-1 14a2 2 0 0 1-2 2H8a2 2 0 0 1-2-2L5 6"/><path d="M10 11v6M14 11v6"/><path d="M9 6V4a1 1 0 0 1 1-1h4a1 1 0 0 1 1 1v2"/>
              </svg>
              <span>مسح</span>
            </button>
          )}
        </div>
      </div>

      {showSQL && (
        <div className="modal-overlay" onClick={() => setShowSQL(false)}>
          <div className="modal glass-panel" onClick={e => e.stopPropagation()}>
            <div className="modal-header">
              <h3>📄 تصدير SQL</h3>
              <button className="modal-close" onClick={() => setShowSQL(false)}>✕</button>
            </div>
            <pre className="sql-output">{sql}</pre>
            <div className="modal-footer">
              <button className="tb-btn tb-btn-blue" onClick={copySQL}>
                {copied ? '✅ تم النسخ!' : '📋 نسخ للحافظة'}
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
